# operator assignment
a = 5
print("nilai a adalah ",a)

a += 1 # artinya adalah a = a + 1
print("nilai a += 1, nilai a menjadi ", a)

a -= 2 # artinya adalah a = a - 2
print("nilai a -= 2, nilai a menjadi ", a)

a *= 5 # artinya adalah a = a * 5
print("nilai a *= 5, nilai a menjadi ", a)

a /= 2 # artinya adalah a = a / 2
print("nilai a /= 2, nilai a menjadi ", a)

b = 10
print("\nnilai b adalah ",b)
b %= 3 # artinya adalah b = b % 3
print("nilai b %= 3, nilai menjadi ", b)


b = 10
print("\nnilai b adalah ",b)
b //= 3 # artinya adalah b = b // 3
print("nilai b //= 3, nilai menjadi ", b)


b = 5
print("\nnilai b adalah ",b)
b **= 3 # artinya adalah b = b**3
print("nilai b //= 3, nilai menjadi ", b)

# operasi bitwise
# OR
c = True
print("\nnilai c adalah ",c)
c |= False # artinya adalah c = c | False
print("nilai c |= False, nilai menjadi ", c)
c = False
print("nilai c adalah ",c)
c |= False # artinya adalah c = c | False
print("nilai c |= False, nilai menjadi ", c)

# AND
c = True
print("\nnilai c adalah ",c)
c &= False # artinya adalah c = c & False
print("nilai c &= False, nilai menjadi ", c)
c = False
print("nilai c adalah ",c)
c &= False # artinya adalah c = c & False
print("nilai c &= False, nilai menjadi ", c)
c = True
print("nilai c adalah ",c)
c &= True # artinya adalah c = c & True
print("nilai c &= False, nilai menjadi ", c)

